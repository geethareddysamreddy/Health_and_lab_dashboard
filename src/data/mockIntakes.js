import { calculateBMI, getBMICategory } from "../utils/bmi";

function buildIntake({ id, status, createdDate, submittedDate, currentQuestionId, answers }) {
  const bmi = calculateBMI(answers.weight, answers.height);
  return {
    id,
    status,
    createdDate,
    submittedDate: submittedDate ?? null,
    currentQuestionId: currentQuestionId ?? "confirmation",
    answers,
    bmi,
    bmiCategory: getBMICategory(bmi),
  };
}

